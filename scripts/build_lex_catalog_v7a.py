def toks(block):
    return [w for w in block.split() if w]


def main():
    v6 = set(json.loads(V6STATS.read_text(encoding="utf-8"))["per_term"])
    cat = {}          # term -> class (mục đầu thắng)

    def add(term, cls):
        term = term.strip()
        if not term or term in cat or term in v6:
            return
        # luật an toàn độ dài
        core = term.replace("PTA", "").replace("QR", "").replace("18", "")
        if len(term) < 3:
            return
        if len(term) == 3 and not KANJI.match(term):
            return
        if KATA_ONLY.match(term):      # katakana thuần vòng 6 đã càn
            return
        cat[term] = cls

    # 1) tái dùng kho idiom cũ
    n_ono = 0
    for line in GLOSS.open(encoding="utf-8"):
        try:
            o = json.loads(line)
        except Exception:
            continue
        c = str(o.get("cat", ""))
        ja = o.get("ja", "").strip()
        if "オノマトペ" in c:
            n_ono += 1
            continue
        if not JAOK.match(ja):
            continue
        if "四字熟語" in c:
            add(ja, "yoji")
        elif "ことわざ" in c:
            add(ja, "kotowaza")
        else:
            add(ja, "kanyouku")

    n_reused = len(cat)
    for w in toks(YOJI):
        add(w, "yoji")
    for w in toks(CULTURE):
        add(w, "culture")
    for w in toks(SUFFIX):
        add(w, "suffix")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for t, c in cat.items():
            f.write(f"{t}\t{c}\n")

    from collections import Counter
    cc = Counter(cat.values())
    print(f"tái dùng idiom_glosses: {n_reused} (bỏ {n_ono} オノマトペ)")
    print(f"tổng danh mục: {len(cat)} -> {OUT}")
    for k, v in cc.most_common():
        print(f"  {k:<10}{v:>6,}")


if __name__ == "__main__":
    main()
